"""
Смета по реальному ТЗ (Большой Головин переулок, 15) — с самостоятельной
оценкой количества расходных материалов по площади и графику уборки,
как просил пользователь, раз в самом ТЗ (Приложение 6) числа не даны.

============================== Как получены базовые цифры ==============================
Площадь объекта и количество дней уборки НЕ додуманы — они математически точно
выводятся из "Перечня объектов закупки" (Приложение 1): там для каждого месяца
контракта указан "Объём услуг" в кв.м. Разделив каждое месячное значение на
1002,6 — получается РОВНО целое число (проверено на всех 36 месяцах контракта,
см. чат) — это количество дней уборки в этом месяце (с поправкой на российские
праздники). Значит 1002,6 кв.м — это реальная площадь объекта, а месячные числа
из Приложения 1 — это (площадь × количество дней уборки), а не сама площадь.
Это ровно тот урок, что уже зафиксирован в tender-agent-architecture.md.

============================== Что дальше — оценка, не факт ==============================
Норматива, который покрывал бы расход ВСЕХ 11 позиций Приложения 6 (мешки,
моющие/чистящие/дезинфицирующие средства, салфетки, инвентарь), не существует
в виде одного документа — в отличие от площади и дней уборки, эти коэффициенты
я не могу вывести математически из самого ТЗ, поэтому они ниже — обоснованные,
но приблизительные допущения. Каждое явно откомментировано. Правильный процесс:
эксперт по клинингу должен их поправить по факту осмотра объекта (сколько
реально мусорных корзин, окон, унитазов и т.д.) — агент даёт стартовую оценку,
а не финальное число.
"""
import math
from datetime import date

from models import TZItem
from price_parser import load_almin_price_list, load_general_opt_price_list
from resolver import resolve_all
from smeta_export import LaborCostInput, SmetaMeta, export_smeta_to_xlsx
from supplier_fallback import stub_supplier_adapter

# --- Базовые величины, выведенные из самого ТЗ (см. docstring выше) ---
AREA_SQM = 1002.6           # реальная площадь объекта — математически точно из Приложения 1
CLEANING_DAYS = 742         # суммарное кол-во дней уборки за весь контракт (36 мес, 2026-11 — 2029-10)
GENERAL_DAYS = 148          # из них — генеральная уборка (раз в неделю по пятницам, с поправкой на праздники)
STAFF_COUNT = 2             # "не менее 2 человек" — прямая цитата из ТЗ
CONTRACT_MONTHS = 36        # 01.11.2026 — 31.10.2029, точно по датам из Приложения 1
CONTRACT_WEEKS = CONTRACT_MONTHS * 52 / 12  # ≈ 156, для позиций с расходом "в неделю"

# --- Допущения по нормам расхода (ЯВНО не из ГОСТа — единого норматива на все
#     11 позиций не существует; см. docstring). Каждое — точка для правки эксперта.
SANITARY_AREA_FRACTION = 0.07   # доля площади под санитарные помещения — типовой ориентир для офиса
SANITARY_AREA = AREA_SQM * SANITARY_AREA_FRACTION
BIN_DENSITY_SQM = 25            # 1 мусорная корзина на ~25 кв.м — офисная норма плотности

tz_items = [
    TZItem(
        raw_name="Пакеты для мусора. Объём 120 л. Размер 70x110 см. Материал ПВД. Плотность 50 мкм",
        # Крупные пакеты — для транспортировки отходов к местам накопления (п.3.1 ТЗ),
        # не для внутренних корзин. 1 пакет/день уборки на весь объект.
        qty=1 * CLEANING_DAYS,
        unit="шт",
    ),
    TZItem(
        raw_name="Пакеты для мусора. Объём 30 л. Размер 48x57 см. Материал ПНД. Плотность 7 мкм. Цвет чёрный",
        # Мелкие пакеты — для внутренних мусорных корзин, меняются при каждой уборке (п.3.1).
        # Количество корзин не указано в ТЗ — оценка по плотности размещения.
        qty=round(AREA_SQM / BIN_DENSITY_SQM) * CLEANING_DAYS,
        unit="шт",
    ),
    TZItem(
        raw_name="Моющее средство для полов и стен. Антимикробный эффект. Без хлора. Без отдушки",
        # Полы моются по всей площади при каждой уборке. Норма 5 мл готового
        # раствора/концентрата на 1 кв.м за одну уборку — типовой проф. ориентир.
        qty=round(AREA_SQM * CLEANING_DAYS * 5 / 1000, 1),
        unit="л",
    ),
    TZItem(
        raw_name="Чистящее средство для унитаза. С дезинфекцией",
        # Привязано к площади санитарных помещений (доля от общей), не ко всему объекту.
        qty=round(SANITARY_AREA * CLEANING_DAYS * 8 / 1000, 1),
        unit="л",
    ),
    TZItem(
        raw_name="Чистящее средство для сантехники. Без хлора",
        qty=round(SANITARY_AREA * CLEANING_DAYS * 6 / 1000, 1),
        unit="л",
    ),
    TZItem(
        raw_name="Дезинфицирующее средство для твёрдых поверхностей, инвентаря, приборов",
        # Дезинфекция — прежде всего часть ГЕНЕРАЛЬНОЙ уборки (глубокая обработка),
        # а не каждого ежедневного прохода — привязано к GENERAL_DAYS, не CLEANING_DAYS.
        qty=round(AREA_SQM * GENERAL_DAYS * 3 / 1000, 1),
        unit="л",
    ),
    TZItem(
        raw_name="Чистящее средство для интерьера",
        # Протирка мебели/подоконников/поверхностей — по всей площади, при каждой уборке.
        qty=round(AREA_SQM * CLEANING_DAYS * 3 / 1000, 1),
        unit="л",
    ),
    TZItem(
        raw_name="Чистящее средство для оргтехники",
        # Не масштабируется площадью (число единиц оргтехники в ТЗ не указано) —
        # фиксированная ежемесячная норма для объекта такого размера.
        qty=round(2.0 * CONTRACT_MONTHS, 1),
        unit="л",
    ),
    TZItem(
        raw_name="Средство для мойки стёкол и зеркал",
        # Тоже не по площади пола (площадь остекления в ТЗ не дана) — фиксированная
        # ежемесячная норма.
        qty=round(1.5 * CONTRACT_MONTHS, 1),
        unit="л",
    ),
    TZItem(
        raw_name="Салфетки универсальные. Материал микрофибра",
        # Расходуется на сотрудника в неделю (не на площадь) — многоразовый инвентарь
        # с регулярной заменой изношенных.
        qty=round(1 * STAFF_COUNT * CONTRACT_WEEKS),
        unit="шт",
    ),
    TZItem(
        raw_name="Комплект для уборки (швабра, ведро) для влажной уборки",
        # Долговечный инвентарь, не расходник день-в-день: 1 комплект на сотрудника
        # + 1 резервный на весь контракт.
        qty=STAFF_COUNT + 1,
        unit="шт",
    ),
]

price_lists = (
    load_almin_price_list(discount_pct=5.0)
    + load_general_opt_price_list(supplier="ТК Сервис", discount_pct=0.0)
)

results = resolve_all(tz_items, price_lists, supplier_adapters={"almin": stub_supplier_adapter})

labor = LaborCostInput(
    monthly_salary=0,  # ЗАПОЛНИТЬ: нет таблицы ставок по региону/сложности (открытый TODO)
    staff_count_by_area=0,
    staff_count_by_hours=0,
    staff_count_recommended=STAFF_COUNT,
    contract_duration_months=CONTRACT_MONTHS,
)

meta = SmetaMeta(
    object_name="Оказание услуг по уборке помещений в 2026-2029 годах — Москва, Большой Головин переулок, 15",
    region="Москва",
    tender_url="Техническое_задание_17204828-1.pdf",
    prepared_date=date.today(),
)

export_smeta_to_xlsx(results, labor, meta, "smeta_golovin_v2.xlsx")
print("Смета сохранена: smeta_golovin_v2.xlsx")
print(f"Площадь: {AREA_SQM} кв.м | Дней уборки: {CLEANING_DAYS} | Из них генеральных: {GENERAL_DAYS}")
