"""
Парсинг прайс-листов поставщиков в единый формат PriceListItem.

В проде эта часть будет опираться на pdf/xlsx-скиллы для извлечения таблицы
из файла произвольного формата. Здесь — функция нормализации ОДНОЙ строки
прайса (артикул, наименование, кол-во в упаковке, цена) в PriceListItem,
плюс уже извлечённые вручную данные из примера "Прайс.pdf" (Альмин Провижн Сервис)
как referen­ce-датасет для тестирования matcher'а.
"""
import re
from typing import Optional

from models import PriceListItem, Source


def parse_price_row(
    supplier: str,
    raw_name_with_sku: str,
    price: float,
    unit: str = "шт",
    discount_pct: float = 0.0,
) -> PriceListItem:
    """
    Прайсы обычно дают наименование в формате:
      "Г-Т0024, Бумага туалетная 1-сл h90 d160 мм 200 м/рул ЭКОНОМ ... "NN" 1/12"
    где первый токен до запятой — внутренний артикул поставщика,
    а хвост "1/NN" или "1/NN/NNN" — упаковка/короб.
    """
    sku = None
    name = raw_name_with_sku.strip()

    m = re.match(r"^([A-ZА-Я0-9\-]+),\s*(.+)$", name)
    if m:
        sku, name = m.group(1), m.group(2).strip()

    pack_size = None
    m2 = re.search(r"(\d+/\d+(?:/\d+)?)\s*$", name)
    if m2:
        pack_size = m2.group(1)

    return PriceListItem(
        supplier=supplier,
        name=name,
        sku=sku,
        unit=unit,
        price=price,
        pack_size=pack_size,
        discount_pct=discount_pct,
        source=Source.PRICE_LIST,
    )


