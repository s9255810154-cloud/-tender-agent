# --- Прайс "Прайс_общий_опт.xlsx" ---
# Совсем другая структура: чистая таблица (не текстовая строка с артикулом
# внутри наименования). Колонки (0-индекс, после пропуска шапки):
#   0  = статус номенклатуры (Активный / Под заказ / Акция / Распродажа)
#   4  = внутренний артикул
#   6  = номенклатура (наименование товара)
#   14 = артикул поставщика
#   15 = цена, руб. (с НДС)
# Название компании-поставщика в самом файле не указано — передаётся отдельно.
def load_general_opt_price_list(
    supplier: str,
    path: str = "data/general_opt_price.xlsx",
    discount_pct: float = 0.0,
    include_only_active: bool = False,
) -> list[PriceListItem]:
    import pandas as pd

    df = pd.read_excel(path, sheet_name=0, header=None)
    data = df.iloc[7:]  # первые 7 строк — заголовок/шапка прайса

    items = []
    for _, row in data.iterrows():
        name = row[6]
        price = row[15]
        if pd.isna(name) or pd.isna(price):
            continue
        status = row[0] if pd.notna(row[0]) else None
        if include_only_active and status != "Активный":
            continue
        items.append(
            PriceListItem(
                supplier=supplier,
                name=str(name).strip(),
                sku=str(row[4]) if pd.notna(row[4]) else None,
                unit="шт",
                price=float(price),
                pack_size=None,
                discount_pct=discount_pct,
                source=Source.PRICE_LIST,
            )
        )
    return items


